"""
scorecard.py
------------
Turns the results dict/json produced by run_analysis.py into a single markdown
"Experimentation Health Scorecard" - the kind of one-page artifact a data/growth
team could actually run quarterly against their real experiment logs.
"""
import json


def render_scorecard(results, out_path="Experimentation_Health_Scorecard.md"):
    r = results

    def pct(x, nd=1):
        return f"{x:.{nd}f}%" if isinstance(x, (int, float)) else str(x)

    def grade(value, good, warn):
        # lower-is-better metrics: value <= good -> green, <= warn -> yellow, else red
        if value <= good:
            return "🟢 Healthy"
        elif value <= warn:
            return "🟡 Watch"
        else:
            return "🔴 At risk"

    md = f"""# Experimentation Health Scorecard
*Simulated program: 200 experiments, known ground truth. Generated by `experiment_autopsy`.*

| # | Check | Result | Status |
|---|-------|--------|--------|
| 1 | False positive rate under daily peeking | {pct(r['fpr_peeking_naive']*100)} (vs. nominal 5%) | {grade(r['fpr_peeking_naive'], 0.06, 0.12)} |
| 1b | False positive rate, fixed-horizon (no peeking) | {pct(r['fpr_fixed_horizon']*100)} | {grade(r['fpr_fixed_horizon'], 0.06, 0.12)} |
| 1c | Exploratory mixture-test prototype (not validated as always-valid) | {pct(r['fpr_msprt_prototype']*100)} | {'⚠️ Exploratory; calibration incomplete'} |
| 2 | Minimum detectable relative lift at current traffic (14-day test, {r['n_per_arm_available_14days']:,} users/arm) | {pct(r['mde_relative_at_current_traffic']*100)} | — |
| 2b | Days needed to reliably detect a 5% relative lift | {r['days_needed_for_5pct_lift']} days | {grade(r['days_needed_for_5pct_lift'], 21, 45)} |
| 3 | Experiments flagged for Sample Ratio Mismatch (p<0.01) | {pct(r['pct_experiments_srm_flagged'])} of program | {grade(r['pct_experiments_srm_flagged'], 3, 8)} |
| 3b | SRM detection recall (of experiments we know are actually bugged) | {pct(r['srm_detection_recall_pct'])} | {grade(100-r['srm_detection_recall_pct'], 5, 20)} |
| 3c | Declared "winners" that were sitting on an undetected/undiagnosed SRM bug | {r['n_declared_winners_with_srm_bug']} of {r['n_declared_winners_peeking']} | {grade(r['n_declared_winners_with_srm_bug'], 0, 3)} |
| 4 | CUPED variance reduction (revenue-style metric, pre/post correlation 0.6) | {pct(r['cuped_variance_reduction_pct'])} | 🟢 Adopt |
| 4b | Runtime reduction from CUPED, same %, applied to the 5%-lift test above | {r['days_to_detect_5pct_lift_before_cuped']} days &rarr; {r['days_to_detect_5pct_lift_after_cuped']} days | 🟢 Adopt |
| 5 | Novelty/decay effects present among true winners (simulated ground truth) | {pct(r['pct_true_winners_with_novelty'])} | — |
| 5b | Novelty detection recall (time-slice interaction test) | {pct(r['pct_novelty_correctly_flagged'])} | 🔴 Underpowered |
| 5c | False novelty alarms on genuinely stable winners | {pct(r['pct_false_novelty_alarms_on_stable_winners'])} | 🟢 Low |
| 6 | False positive rate checking 5 metrics per test, no correction | {pct(r['multi_metric_naive_fpr_5metrics']*100)} | {grade(r['multi_metric_naive_fpr_5metrics'], 0.06, 0.12)} |
| 6b | Same, with Benjamini-Hochberg correction | {pct(r['multi_metric_bh_fpr_5metrics']*100)} | {grade(r['multi_metric_bh_fpr_5metrics'], 0.06, 0.12)} |

## Headline
Out of {r['n_declared_winners_peeking']} experiments declared "significant winners" under a
stop-when-significant policy, **{r['n_false_positive_winners']} ({pct(r['pct_declared_winners_that_are_false'])})
were false positives** (ground truth: no real effect). Running the identical 200
experiments under a disciplined fixed-horizon policy would have declared only
{r['n_declared_winners_fixed_horizon']} winners, of which {pct(r['pct_declared_winners_that_are_false_fixed_horizon'])} were false -
fewer false wins in absolute terms, at the cost of also missing some real ones that
peeking caught early (peeking isn't pure downside, it's a power/validity trade you're
currently making blind).

## Known limitations of this scorecard
- Ground truth is simulator-defined. Real programs don't get this, which is exactly why
  checks 1, 3, and 6 (process controls) matter more than any single p-value.
- Novelty detection recall ({pct(r['pct_novelty_correctly_flagged'])}) is genuinely low here - not a bug,
  a finding. Detecting decay effects needs meaningfully more data than detecting the
  headline effect; don't expect a time-slice test to catch most novelty effects at
  typical 2-week experiment sample sizes.
- CUPED's payoff is metric-dependent. It was demonstrated here on a continuous,
  revenue-style metric with a realistic 0.6 pre/post correlation; a low-correlation or
  purely binary metric will see much less benefit (see memo).
"""
    with open(out_path, "w") as f:
        f.write(md)
    return md


if __name__ == "__main__":
    with open("results.json") as f:
        results = json.load(f)
    render_scorecard(results)
    print("scorecard written")
